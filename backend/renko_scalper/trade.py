"""Trade lifecycle shared by the live tracker and the backtester (so they cannot diverge).

Two-unit plan (Miner): unit 1 exits at TP1 (default 1R), then the stop moves to
breakeven (+fees, as in Wyckoff's rule of covering costs); unit 2 runs with a Renko-style
trail 2 bricks behind the extreme and is only closed when the market takes it out.
Within a single candle the stop is assumed to be hit before any target (conservative).
"""
from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Optional

from .models import Candle


@dataclass
class TradeState:
    side: int
    entry: float
    stop: float  # current protective stop
    stop0: float  # initial stop (defines 1R)
    tp1: float
    brick: float
    fee_pct: float  # per side
    status: str = "open"  # open -> tp1 -> closed
    tp1_hit: bool = False
    extreme: float = 0.0
    unit1_r: float = 0.0
    result_r: Optional[float] = None
    exit_reason: str = ""
    bars: int = 0
    last_ts: int = 0
    events: list = field(default_factory=list)

    def to_dict(self) -> dict:
        d = asdict(self)
        d.pop("events", None)
        return d

    @classmethod
    def from_dict(cls, d: dict) -> "TradeState":
        d = dict(d)
        d.pop("events", None)
        return cls(**d)

    @property
    def r_dist(self) -> float:
        return abs(self.entry - self.stop0)

    def _unit_r(self, exit_price: float) -> float:
        fee = self.entry * self.fee_pct / 100.0 * 2.0
        return ((exit_price - self.entry) * self.side - fee) / self.r_dist


def new_trade(side: int, entry: float, stop: float, tp1: float, brick: float, fee_pct: float) -> TradeState:
    return TradeState(side=side, entry=entry, stop=stop, stop0=stop, tp1=tp1, brick=brick, fee_pct=fee_pct, extreme=entry)


def advance(st: TradeState, c: Candle) -> list:
    """Feed one closed candle; returns a list of event strings generated by this candle."""
    ev: list = []
    if st.status == "closed":
        return ev
    st.bars += 1
    st.last_ts = c.ts
    s = st.side

    # 1) stop first (conservative); gaps fill at the open if worse than the stop
    hit = (c.l <= st.stop) if s > 0 else (c.h >= st.stop)
    if hit:
        px = min(c.o, st.stop) if s > 0 else max(c.o, st.stop)
        r_unit = st._unit_r(px)
        if st.tp1_hit:
            st.result_r = 0.5 * st.unit1_r + 0.5 * r_unit
            st.exit_reason = "runner_exit"
            ev.append("runner_exit")
        else:
            st.result_r = r_unit
            st.exit_reason = "stopped"
            ev.append("stopped")
        st.status = "closed"
        st.events.extend(ev)
        return ev

    # 2) TP1
    if not st.tp1_hit:
        reached = (c.h >= st.tp1) if s > 0 else (c.l <= st.tp1)
        if reached:
            st.tp1_hit = True
            st.status = "tp1"
            st.unit1_r = st._unit_r(st.tp1)
            be = st.entry + s * st.entry * st.fee_pct / 100.0 * 2.0
            st.stop = max(st.stop, be) if s > 0 else min(st.stop, be)
            st.extreme = c.h if s > 0 else c.l
            ev.append("tp1")
    else:
        # 3) trail: 2 bricks behind the best price seen so far
        st.extreme = max(st.extreme, c.h) if s > 0 else min(st.extreme, c.l)
        trail = st.extreme - s * 2.0 * st.brick
        st.stop = max(st.stop, trail) if s > 0 else min(st.stop, trail)
        # trail updates are silent; the current stop is exposed through the API
    st.events.extend(ev)
    return ev
